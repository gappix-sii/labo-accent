import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const url = process.argv[2], shots = process.argv[3] || '/tmp';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args:['--no-sandbox','--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream','--use-file-for-fake-audio-capture=/home/claude/labo/test/fake.wav'] });
const ctx = await b.newContext({ viewport:{width:390,height:844}, deviceScaleFactor:2, permissions:['microphone'] });
const p = await ctx.newPage();
const logs=[]; p.on('console', m=>{ if(m.type()!=='debug') logs.push(m.type()+': '+m.text()); }); p.on('pageerror', e=>logs.push('pageerror: '+e.message));
await p.goto(url);
await p.waitForTimeout(800);
await p.screenshot({path: shots+'/1-home.png', fullPage:true});
await p.click('#prep').catch(()=>logs.push('no prep button'));
await p.waitForFunction(()=>document.getElementById('engine').dataset.state==='ready',null,{timeout:30000}).catch(()=>logs.push('ENGINE NOT READY: '+'?'));
await p.click('nav.bottom button[data-go=practice]');
await p.waitForTimeout(300);
await p.screenshot({path: shots+'/2-practice.png', fullPage:true});
await p.click('[data-cat=travel]');
await p.waitForTimeout(800);
await p.click('#rec');
await p.waitForSelector('#result .score', {timeout:25000}).catch(()=>logs.push('NO RESULT; status='));
logs.push('status: '+await p.textContent('#status'));
await p.screenshot({path: shots+'/3-result.png', fullPage:true});
await p.click('nav.bottom button[data-go=sounds]'); await p.waitForTimeout(300);
await p.screenshot({path: shots+'/4-sounds.png', fullPage:true});
await p.click('nav.bottom button[data-go=settings]'); await p.waitForTimeout(300);
await p.click('#delData'); await p.waitForTimeout(300);
await p.screenshot({path: shots+'/5-confirm.png'});
await p.click('#dlgCancel');
console.log(logs.join('\n'));
await b.close();
